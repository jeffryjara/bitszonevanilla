  function getLanguage() {
    return currentLang;
  }

  function t(key, fallback, params) {
    var str = '';
    if (I18N[currentLang] && I18N[currentLang][key] !== undefined) {
      str = I18N[currentLang][key];
    } else if (I18N.es && I18N.es[key] !== undefined) {
      str = I18N.es[key];
    } else {
      str = (fallback !== undefined) ? fallback : key;
    }
    if (params && typeof params === 'object') {
      Object.keys(params).forEach(function (p) {
        str = str.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
      });
    }
    return str;
  }

  function applyLanguage(lang) {
    if (lang === 'en' || lang === 'es') {
      currentLang = lang;
    }
    if (typeof document === 'undefined') return;

    if (document.documentElement) {
      document.documentElement.lang = currentLang;
    }

    // 1. Textos data-i18n
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = t(key);
      if (val) el.textContent = val;
    });

    // 2. HTML data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      var val = t(key);
      if (val) el.innerHTML = val;
    });

    // 3. Tooltips & Titles data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      var val = t(key);
      if (val) {
        el.setAttribute('title', val);
        if (!el.hasAttribute('aria-label')) {
          el.setAttribute('aria-label', val);
        }
      }
    });

    // 4. Placeholders data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      var val = t(key);
      if (val) el.setAttribute('placeholder', val);
    });

    // 5. Aria-labels data-i18n-aria
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      var val = t(key);
      if (val) el.setAttribute('aria-label', val);
    });

    // Notificar al resto de la app
    try {
      window.dispatchEvent(new CustomEvent('bz:language-changed', { detail: { lang: currentLang } }));
    } catch (e) {}
  }

  window.BitszoneI18n = {
    I18N: I18N,
    t: t,
    getLanguage: getLanguage,
    applyLanguage: applyLanguage
  };

